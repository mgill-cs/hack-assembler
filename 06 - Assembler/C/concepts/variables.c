#include <stdio.h>

int main() {
    int x = 5;          // whole number
    float y = 3.14;     // decimal number
    char c = 'A';       // a single character
    char str[] = "hi";  // a string (array of characters)
    printf("%d\n", x);      // int
    printf("%f\n", y);      // float/double
    printf("%c\n", c);      // char
    printf("%s\n", str);    // string
    return 0;
}